// ─────────────────────────────────────────────────────────────────────────────
// Deleted article slugs: the edge half of the tombstone registry
// ─────────────────────────────────────────────────────────────────────────────
//
// A deleted article used to answer 404, and a 404 is a "come back later"
// signal to a crawler: Google keeps retrying the URL for weeks, the sitemap
// drops it slowly, and the dead test document lingers in the index the whole
// time. HTTP 410 Gone is the explicit "this resource is permanently removed"
// answer, and it is what a search engine needs to drop a URL immediately.
//
// The registry has two halves, and this module is the edge one:
//
//   • THIS file — the compiled-in half. Known deleted slugs and the slug
//     shapes that only ever came from a fixture or a duplicate action.
//     It is deliberately free of imports (no database driver, no next/cache)
//     so the middleware can evaluate it on every request at the edge
//     without waking Neon PostgreSQL or touching any I/O at all.
//
//   • lib/tombstones.ts — the server half. Slugs an admin deletes from the
//     dashboard are written to a tombstone table there and read through an
//     unstable_cache entry, so the middleware learns about them from a
//     cached manifest (see app/api/deleted-slugs/route.ts) instead of a
//     per-request database query.
//
// The two halves are kept separate on purpose: anything the middleware
// imports statically becomes part of the Worker bundle, and the database
// drivers must never end up there.
// ─────────────────────────────────────────────────────────────────────────────

import { GHOST_SLUG_EXACT } from "./ghost-content";

// Fixture slugs that were published by mistake and have since been deleted.
// These are the exact URLs the newsroom knows are gone — the Tiptap editor
// testing documents (deleted fixtures that are still in Google's index) and
// the generic fixture shapes the ghost-content sweeps (lib/ghost-content.ts)
// have been deleting for as long as the CMS has run. The fixture list is
// imported rather than duplicated so this registry and the cleanup tool
// cannot drift apart.
export const KNOWN_DELETED_SLUGS: readonly string[] = [
  // The Tiptap editor test documents.
  "tiptap-editor",
  "ultimate-testing-document",
  "tiptap-editor-ultimate-testing-document",
  // Every slug the ghost-content classifier treats as a fixture on its
  // own, with no other evidence needed.
  ...GHOST_SLUG_EXACT,
];

/**
 * Slug shapes that can only come from a fixture generator or a "duplicate"
 * click, never from a real headline.
 *
 * Anchored on purpose, and deliberately narrower than the shapes the
 * ghost-content *sweeper* reports: a 410 is a de-indexing instruction, so a
 * false positive here would bury a real story. `test-data-breaches-at-
 * github` and `sample-rate-conversion-in-audio` are real headlines that
 * happen to start with a fixture word, which is why bare `test-` / `sample-`
 * prefixes are NOT matched — only whole-slug fixtures and the unambiguous
 * prefixes (`tmp-`, `copy-of-`, …) that no editor would ever publish.
 */
export const DELETED_SLUG_PATTERNS: readonly RegExp[] = [
  // A fixture word alone, optionally numbered by the generator: test,
  // test-2, testing_3, dummy, sample-4 …
  /^(test|testing|dummy|sample|untitled)(-|_)?\d*$/,
  // Generator and duplicate-action prefixes. Strong signals only.
  /^(tmp|temp|copy-of|untitled|lorem-ipsum)-/,
  // Autogenerated placeholder shapes.
  /^(article|post|draft)-\d+$/,
];

/**
 * Is this slug a known, permanently deleted article?
 *
 * Pure and synchronous: the middleware runs it on every /article/* request
 * with zero I/O, which is what keeps a 410 from waking the database.
 * Dynamic tombstones (slugs deleted from the dashboard at runtime) are not
 * visible here — they live in lib/tombstones.ts and reach the edge through
 * the cached manifest endpoint.
 */
export function isDeletedSlug(slug: string | null | undefined): boolean {
  if (!slug) return false;
  const normalized = slug.trim().toLowerCase();
  if (!normalized) return false;
  if (KNOWN_DELETED_SLUGS.includes(normalized)) return true;
  return DELETED_SLUG_PATTERNS.some((pattern) => pattern.test(normalized));
}
